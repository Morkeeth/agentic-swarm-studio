"""Hand the fix back as a test. Reads one swarm result, writes a Playwright test that replays the clicks a visitor made.

The test fails while the page a visitor reached answers with an error, and passes once it loads with content.
It replays clicks by their visible label only. It never types, signs in or sends a form.
"""
import json, re

ERROR = ('error_page',)


def _visitors(result):
    for group in result.get('tries') or []:
        for v in group: yield v


def path_of(visitor):
    """The labels a visitor clicked, in order, up to and including the first click that hit an error page."""
    labels = []
    for s in visitor.get('steps', []):
        if s.get('action') == 'click' and s.get('target_text') and s.get('status') in ('ok', 'error_page'):
            labels.append(s['target_text'])
            if s['status'] in ERROR: return labels, s
    return labels, None


def pick(result):
    """The visitor whose path says most: one that hit an error page first, else the longest click path."""
    best = None
    for v in _visitors(result):
        labels, hit = path_of(v)
        if not labels: continue
        rank = (hit is not None, len(labels))
        if best is None or rank > best[0]: best = (rank, v, labels, hit)
    return best


def generate(result):
    """Python source of one pytest file, or None when no visitor clicked anything."""
    best = pick(result)
    if not best: return None
    _, v, labels, hit = best
    selectors = [s.get('target_locator') for s in v.get('steps', []) if s.get('action') == 'click' and s.get('target_text') and s.get('status') in ('ok', 'error_page')][:len(labels)]
    viewport = v.get('viewport') or ([390, 844] if v.get('phone') else [1440, 900])
    if len(viewport) != 2 or any(not isinstance(x, int) or x < 100 or x > 4000 for x in viewport): raise ValueError('Invalid retained viewport.')
    start = result['url']
    last = next((s for s in reversed(v.get('steps', [])) if s.get('say')), {})
    what = (hit or {}).get('hit', {}).get('what_happened') if hit else None
    said = (last.get('wish') or last.get('say') or '').replace('\n', ' ')[:160]
    name = re.sub(r'[^a-z0-9]+', '_', ' '.join(labels).lower()).strip('_')[:50] or 'path'
    lines = [
        f'"""Generated by Agentic Swarm Simulator from run {result.get("id", "unknown")}.',
        '',
        f'Visitor: {v["name"]}. Goal: {v["goal"]}.',
        f'Outcome: {v.get("outcome")}.' + (f' {what}' if what else ''),
        *([f'Last words: "{said}"'] if said else []),
        'Navigation smoke check only. A pass does not establish task completion.',
        'Red while a page on this path answers with an error; no error is presumed.',
        'Run: pip install pytest playwright && playwright install chromium && pytest this_file.py',
        '"""',
        'import os, re',
        'from playwright.sync_api import sync_playwright, expect',
        '',
        f'START = os.environ.get("SWARM_START_URL", {json.dumps(start)})',
        f'PATH = {json.dumps(labels)}',
        f'SELECTORS = {repr(selectors)}',
        '',
        '',
        f'def test_visitor_path_{name}():',
        '    with sync_playwright() as pw:',
        '        browser = pw.chromium.launch(headless=True)',
        f'        page = browser.new_page(viewport={{"width": {viewport[0]}, "height": {viewport[1]}}})',
        '        status = {}',
        '        page.on("response", lambda r: status.__setitem__("last", r.status) if r.request.is_navigation_request() and r.frame == page.main_frame else None)',
        '        first = page.goto(START, wait_until="domcontentloaded")',
        '        assert first is not None and first.status < 400, f"start page answered {first.status if first else None}"',
        '        for index, label in enumerate(PATH):',
        '            status.pop("last", None)',
        '            # Whole label, any case: the visitor read rendered text, which CSS text-transform can change from the accessible name.',
        '            name = re.compile("^" + re.escape(label) + "$", re.I)',
        '            target = page.get_by_role("link", name=name).or_(page.get_by_role("button", name=name)).or_(page.get_by_role("tab", name=name)).or_(page.locator("summary").filter(has_text=name))',
        '            if SELECTORS[index]:',
        '                target = page.locator(SELECTORS[index]).and_(page.locator("a[href],button,[role=button],[role=link],[role=tab],summary")).filter(has_text=name)',
        '            expect(target).to_have_count(1, timeout=8000)',
        '            assert target.count() == 1, f"recorded control missing or ambiguous: {label!r}"',
        '            target.click()',
        '            page.wait_for_load_state("domcontentloaded")',
        '            code = status.get("last", 200)',
        '            assert code < 400, f"clicking {label!r} opened a page that answered {code}"',
        '        text = page.locator("body").inner_text().strip()',
        '        assert len(text) > 40, "the last page on the path has almost no text"',
        '        browser.close()',
        '',
    ]
    return '\n'.join(lines)

